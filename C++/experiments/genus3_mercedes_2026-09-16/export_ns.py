"""Independent all-NS central-vertex data for the genus-three test."""
from pathlib import Path
from itertools import product
import hashlib, json, sys, time

D = Path(__file__).resolve().parent
ROOT = D.parents[2]
for sub in ['c_Recursion', 'genus_2_cross_channel', 'double_virasoro/all_ns']:
    sys.path.insert(0, str(ROOT/'Code'/sub))
from ns_genus12_finite_c_check import NumericNSVermaModule, NSDescendantThreeForm
from two_virasoro_fusion import ns_fusion_data
from free_majorana_pair_of_pants import majorana_three_point

start = time.perf_counter()
b = 7/5
momenta = (11/23, 13/29, 17/31)
q = b+1/b
h = tuple(q*q/8-p*p/2 for p in momenta)
c = 1.5+3*q*q
modules = [NumericNSVermaModule(c=c, weight=x) for x in h]
form = NSDescendantThreeForm(c=c, bra_weight=h[0], middle_weight=h[1], ket_weight=h[2])
physical = []
branch = []
for levels in product(range(3), repeat=3):
    states = [modules[e].basis(levels[e]) for e in range(3)]
    assert all(len(s)==1 for s in states)
    physical.append(complex(form.value(*(s[0] for s in states))))
for labels in product((-1,0,1), repeat=3):
    data = ns_fusion_data(b=b, p1=momenta[0], p2=momenta[1], p3=momenta[2],
                         k1=labels[0], k2=labels[1], k3=labels[2], precision=40)
    branch.append(complex(data.numerator))
# The human auxiliary BPZ form has norm -1 on psi_-1/2|0>.
# The raw sphere Pfaffian needs the bra-slot BPZ sign, exactly as in
# check_second_virasoro_primary.current_fermion_three_point.
fermion = [complex((-1)**bits[0]*majorana_three_point(*((1,) if x else () for x in bits)))
           for bits in product(range(2), repeat=3)]
def row(name, values):
    return f'const S {name}[] = {{'+','.join(f'S({z.real:.17g},{z.imag:.17g})' for z in values)+'};\n'
(D/'central_data.hpp').write_text('// Generated by export_ns.py; machine precision boundary data.\n'
                                +row('central_physical', physical)
                                +row('central_branch', branch)
                                +row('central_fermion', fermion))
sources = [Path(__file__)] + [Path(m.__file__) for m in list(sys.modules.values())
          if getattr(m,'__file__',None) and str(m.__file__).startswith(str(ROOT/'Code'))]
result = dict(b=b, momenta=momenta, elapsed_seconds=time.perf_counter()-start,
              physical_vertices=len(physical), branching_vertices=len(branch),
              fermion_vertices=len(fermion),
              precision='machine complex double; 40-digit NS branching polynomials',
              source_sha256={str(p.relative_to(ROOT)):hashlib.sha256(p.read_bytes()).hexdigest()
                             for p in sources})
(D/'central_manifest.json').write_text(json.dumps(result,indent=2)+'\n')
print(json.dumps({k:v for k,v in result.items() if k!='source_sha256'},indent=2))
